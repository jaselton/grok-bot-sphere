#!/usr/bin/env python3
"""Bake the Sphere's watch faces for the firmware: firmware/grok_sphere/face_assets.h

- Each static face (dial art without hands/digits) as a 256-colour indexed image (I8 + RGB565 palette):
  130 KB per face instead of 259 KB of RGB565, so all five fit beside the wake model in the 3 MB app partition.
- Alpha (A8) glyph atlases for the live digits, and A8 text sprites for the caution lights.
The firmware decodes a face into a PSRAM RGB565 canvas and draws the hands/digits on top (faces.cpp).
Usage: make_face_assets.py [OUT_HEADER]
"""
import os, sys
from PIL import Image, ImageFont
from render_watch_dial import render as render_dive, DIN
import render_faces as rf

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "../firmware/grok_sphere/face_assets.h")
FUTURA, DINC = rf.FUTURA, rf.DINC

def rgb565(r, g, b): return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def c_bytes(name, data, ctype="uint8_t"):
    out = [f"static const {ctype} {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 32): out.append("  " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    out.append("};")
    return "\n".join(out)

def face_i8(name, img):
    q = img.convert("RGB").quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:768]; pal += [0] * (768 - len(pal))
    p565 = [rgb565(pal[i * 3], pal[i * 3 + 1], pal[i * 3 + 2]) for i in range(256)]
    return c_bytes(f"{name}_pal", p565, "uint16_t") + "\n" + c_bytes(f"{name}_idx", list(q.tobytes()))

GLYPHS = "0123456789:."
def atlas(name, path, px, index=0):
    f = ImageFont.truetype(path, px, index=index)
    top = min(f.getbbox(c)[1] for c in "0123456789"); bot = max(f.getbbox(c)[3] for c in "0123456789")
    h = bot - top; parts, meta, off = [], [], 0
    for ch in GLYPHS:
        w = max(1, int(round(f.getlength(ch))))
        im = Image.new("L", (w, h), 0)
        from PIL import ImageDraw
        ImageDraw.Draw(im).text((0, -top), ch, font=f, fill=255)
        parts += list(im.tobytes()); meta.append((off, w)); off += w * h
    s = c_bytes(f"{name}_a8", parts) + "\n"
    s += f"static const FaceGlyph {name}_g[{len(GLYPHS)}] = {{" + ",".join(f"{{{o},{w}}}" for o, w in meta) + "};\n"
    s += f"static const FaceFont {name} = {{ {name}_a8, {name}_g, {h} }};"
    return s

def sprite(name, text, path, px, index=0):
    from PIL import ImageDraw
    f = ImageFont.truetype(path, px, index=index)
    l, t, r, b = f.getbbox(text); w, h = r - l + 2, b - t + 2
    im = Image.new("L", (w, h), 0); ImageDraw.Draw(im).text((1 - l, 1 - t), text, font=f, fill=255)
    return c_bytes(f"{name}_a8", list(im.tobytes())) + f"\nstatic const FaceSprite {name} = {{ {name}_a8, {w}, {h} }};"

faces = [("face_dive", render_dive("CHARLIE", "Chief of Staff", "DESK CHRONOMETER", "EST. 2026")),
         ("face_timer", rf.huey_timer()), ("face_fuel", rf.huey_fuel()),
         ("face_caution", rf.huey_caution()), ("face_stinger", rf.stinger())]

parts = ["#pragma once", "// GENERATED by tools/make_face_assets.py. Do not edit.", "#include <stdint.h>",
         "struct FaceGlyph { uint32_t off; uint16_t w; };",
         "struct FaceFont { const uint8_t* a8; const FaceGlyph* g; uint16_t h; };   // glyphs: \"" + GLYPHS + "\"",
         "struct FaceSprite { const uint8_t* a8; uint16_t w, h; };"]
for n, im in faces: parts.append(face_i8(n, im))
parts += [atlas("font_timer", DINC, 44), atlas("font_fuel", DINC, 24), atlas("font_caution", DINC, 40), atlas("font_date", DIN, 15)]
parts += [sprite("spr_wake", "WAKE UP", FUTURA, 9, 2), sprite("spr_timeup", "TIME UP", FUTURA, 9, 2),
          sprite("spr_master", "MASTER", FUTURA, 15, 2), sprite("spr_caution", "CAUTION", FUTURA, 15, 2),
          sprite("spr_lowtalk", "5 MIN TALK", FUTURA, 9, 2)]
open(OUT, "w").write("\n".join(parts) + "\n")
print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB source")
