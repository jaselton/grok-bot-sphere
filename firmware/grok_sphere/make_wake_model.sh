#!/bin/sh
# Embeds a microWakeWord .tflite as wake_model.h (git-ignored: the training data is non-commercial).
# Usage: ./make_wake_model.sh path/to/model.tflite "hey charlie" [cutoff]
set -e
M="$1"; NAME="${2:-wake word}"; CUT="${3:-0.90}"
[ -f "$M" ] || { echo "model not found: $M" >&2; exit 1; }
OUT="$(dirname "$0")/wake_model.h"
{
  echo "#pragma once"
  echo "// GENERATED by make_wake_model.sh from $(basename "$M") — do not commit (non-commercial training data)."
  echo "#define WAKE_MODEL_NAME \"$NAME\""
  echo "#define WAKE_MODEL_CUTOFF ${CUT}f"
  echo "alignas(16) static const unsigned char g_wake_model[] = {"
  xxd -i < "$M"
  echo "};"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$M") bytes model, \"$NAME\", cutoff $CUT)"
