#!/bin/sh
# Writes secrets.h (git-ignored) from the macOS Keychain. Run before compiling.
: "${RELAY_URL:?set RELAY_URL, e.g. wss://grok-sphere-relay.<you>.workers.dev/ws}"
# Device token: from the macOS Keychain (security add-generic-password -a grok-sphere -s grok-sphere-device-token -w <token>)
# or from the DEVICE_TOKEN environment variable.
TOK="${DEVICE_TOKEN:-$(security find-generic-password -s grok-sphere-device-token -w 2>/dev/null)}"
[ -n "$TOK" ] || { echo "no device token: set DEVICE_TOKEN or add it to the Keychain" >&2; exit 1; }
cat > "$(dirname "$0")/secrets.h" <<H
#pragma once
// GENERATED by make_secrets.sh from the Keychain. Do not commit.
#define RELAY_URL    "$RELAY_URL"
#define DEVICE_TOKEN "$TOK"
H
echo "secrets.h written"
